// Package release 是本地配方批次与放行台账。
//
// 台账数据保存在调用方指定的本地目录中，不同目录互相独立；
// 程序退出后重新打开同一位置，已登记的数据与请求结果仍完整可查。
// 主要能力：
//
//   - RegisterRecipe：按配方编号与版本号登记配方版本（名称 + 每种物料的每份克数），
//     版本内容不可覆盖；
//   - CreateBatch / UpdateDraftBatch / StartBatch / CloseBatch：批次状态机
//     （草稿 → 执行中 → 已关闭），草稿可改份数与配方，开始执行后固定，
//     只有执行中可以关闭，关闭确认已有投料且不要求数量吻合；
//     读取已保存数据时批次状态必须精确为 draft、executing、closed 之一，
//     缺失、为空、null、其他字符串，或大小写、前后空格与合法值不同，
//     一律按 ErrCorruptData 拒绝整份台账，不猜状态、不补成草稿、不跳过；
//   - AddFeeding：执行中追加投料（物料须属于绑定配方版本），
//     投料按登记顺序保存、不可修改或删除，关闭后不可追加；
//     同一批次不同物料共用从 1 起连续编号的登记序列，读取已保存数据时
//     序号必须与记录位置一致，重号、跳号或位置不符按 ErrCorruptData 拒绝，
//     不按投料时间排序、不自行重排或补号；
//     已保存的投料成功请求，其返回结果必须仍能对应到原批次中序号、物料、
//     克数、投料时间、登记人逐项一致的真实投料；结果缺失、为 null、为空
//     对象，原批次或序号不存在，或任一项与实际记录、原提交内容不符，同样
//     按 ErrCorruptData 拒绝整份台账（克数按数值核对，1.000 与 1 等价；
//     时间按同一时刻核对，时区写法不同不算不一致）；
//     每种物料的累计实投量上限为 9223372036854775.807 克，按物料分别判断；
//   - GetBatch：返回配方版本、计划份数、状态、全部投料，
//     并按物料逐项列出应投量、累计实投量与差额，无投料的物料也会显示；
//   - GetRecipe：查询配方版本。
//
// 所有写入都带请求编号：同一位置内，相同编号与相同操作内容重复提交
// 返回第一次成功的结果；相同编号用于其他操作或不同内容时被拒绝；
// 失败不占用编号，也不留下部分记录。并发提交通过进程内互斥与文件锁
// （flock）串行化，同一请求同时到达只产生一次业务变更。
package release

